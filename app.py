# =====================================================================
# Импорт нужных инструментов (библиотек)
# =====================================================================
from fastapi import FastAPI, HTTPException # FastAPI - сам фреймворк, HTTPException - для отправки ошибок (400, 404)
from fastapi.middleware.cors import CORSMiddleware # CORS - чтобы браузер не блокировал запросы
from pydantic import BaseModel # Pydantic - строгий проверяльщик данных (чтобы прислали именно текст, а не цифры)
import json # Библиотека для работы с форматом JSON (перевод словарей в текст и обратно)
import os   # Библиотека для работы с операционной системой (проверка, есть ли файл на диске)

# Создаем главное приложение (наш сервер)
app = FastAPI()

# =====================================================================
# Настройка CORS (Фейсконтроль сервера)
# =====================================================================
# По умолчанию браузеры запрещают сайту на порту 5500 отправлять данные на порт 8000.
# Этот код говорит браузеру: "Расслабься, мы разрешаем принимать запросы откуда угодно (*)".
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],     # Разрешаем запросы с любых адресов
    allow_credentials=True,
    allow_methods=["*"],     # Разрешаем любые методы (POST, GET и т.д.)
    allow_headers=["*"],     # Разрешаем любые заголовки
)

# =====================================================================
# Описание структуры данных (Схема)
# =====================================================================
# Мы жестко говорим серверу: "Когда фронтенд шлет данные, там ОБЯЗАТЕЛЬНО
# должны быть два поля: name (строка) и password (строка)".
class UserData(BaseModel):
    name: str
    password: str

# Структура данных, которые мы ждем от JS
class ActionData(BaseModel):
    action_type: str
# =====================================================================
# Вспомогательная функция: Чтение файла базы данных
# =====================================================================
def get_users():
    file_path = "users.json" # Название файла, где хранятся юзеры
    
    # Проверяем, существует ли вообще такой файл в папке проекта
    if os.path.exists(file_path):
        # Открываем файл в режиме чтения ("r") с поддержкой русского языка (utf-8)
        with open(file_path, "r", encoding="utf-8") as f:
            try:
                # Пытаемся перевести текст из файла в список Python
                return json.load(f)
            except json.JSONDecodeError:
                # Если файл пустой или в нем какой-то мусор - возвращаем пустой список
                return []
    # Если файла вообще нет, тоже возвращаем пустой список
    return []

# =====================================================================
# РОУТ 1: Регистрация нового пользователя
# =====================================================================
@app.post("/register") # Этот код сработает, когда кто-то постучится на /register методом POST
def register_user(user: UserData):
    # 1. Получаем список всех существующих пользователей из файла
    users = get_users()

    # 2. Проверяем, не занято ли уже такое имя
    for existing_user in users:
        if existing_user["name"] == user.name:
            # Если нашли совпадение - прерываем работу и кидаем ошибку 400 прямо в браузер
            raise HTTPException(status_code=400, detail="Такое имя уже занято!")

    # 3. Если имя свободно, берем данные, которые прислал браузер (user), 
    # превращаем их в словарь (.dict()) и добавляем в конец списка
    users.append(user.dict())

    # 4. Открываем файл в режиме записи ("w"). Режим "w" полностью стирает старый файл 
    # и записывает в него новый, обновленный список
    with open("users.json", "w", encoding="utf-8") as f:
        # indent=4 делает красивый JSON с отступами (лесенкой), чтобы человеку было удобно читать
        json.dump(users, f, ensure_ascii=False, indent=4)

    # 5. Отвечаем браузеру, что всё прошло успешно
    return {"status": "success", "message": f"Пользователь {user.name} зарегистрирован!" , "redirect_to": "../WelcomePage/index.html"}

# =====================================================================
# РОУТ 2: Вход пользователя (Авторизация)
# =====================================================================
@app.post("/login")
def login_user(user: UserData):
    # 1. Достаем всех юзеров из файла
    users = get_users()

    # 2. Ищем пользователя по списку
    for existing_user in users:
        # Проверяем совпадение по имени
        if existing_user["name"] == user.name:
            # Если имя совпало, проверяем совпал ли пароль
            if existing_user["password"] == user.password:
                # Ура, всё совпало! Пускаем.
                return {"status": "success", "message": "Вход выполнен успешно!" , "redirect_to": "../WelcomePage/index.html"}
            else:
                # Имя правильное, но пароль от другого аккаунта. Ошибка 400.
                raise HTTPException(status_code=400, detail="Неверный пароль!")

    # 3. Если цикл перебрал весь список, но так и не нашел такого имени:
    raise HTTPException(status_code=404, detail="Такой пользователь не найден!")


@app.post("/play")
async def handle_action(data: ActionData):
    # Здесь логика сервера. 
    # Например, проверяем, что прислал пользователь.
    if data.action_type == "play":
        # Всё хорошо, говорим фронтенду, что статус success 
        # и даем URL, куда нужно перенаправить пользователя.
        return {"status": "success", "redirect_to": "../Game/game.html"}
    else:
        return {"status": "error", "message": "Неизвестное действие"}




