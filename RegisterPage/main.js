// =====================================================================
// 1. ЗАХВАТ ЭЛЕМЕНТОВ ИЗ HTML
// =====================================================================
// Мы находим теги на странице по их ID, чтобы мы могли читать из них текст или менять их.
const nameInput = document.getElementById("inpt-in-1");       // Поле для ввода Имени
const passwordInput = document.getElementById("inpt-in-2");   // Поле для ввода Пароля
const registerBtn = document.getElementById("sign_btn");      // Кнопка "Зарегистрироваться"
const statusP = document.getElementById("status-p");          // Невидимый тег <p>, куда будем писать ошибки или успех

// =====================================================================
// 2. СЛУШАТЕЛЬ СОБЫТИЙ (КЛИК ПО КНОПКЕ)
// =====================================================================
// Слово "async" говорит, что внутри функции мы будем использовать "await" (ожидание ответа от сервера)
registerBtn.addEventListener("click", async function (event) {
    
    // ВАЖНО: По умолчанию формы в HTML при нажатии на кнопку ПЕРЕЗАГРУЖАЮТ страницу.
    // Нам это не нужно (мы хотим отправить данные тихо в фоне). Эта команда отменяет перезагрузку.
    event.preventDefault();

    // Забираем то, что реально напечатал пользователь (свойство .value)
    const enteredName = nameInput.value;
    const enteredPassword = passwordInput.value;

    // Базовая проверка: если пользователь нажал кнопку, но оставил поля пустыми
    if (!enteredName || !enteredPassword) {
        statusP.innerText = "Заполни все поля!";
        statusP.style.color = "red"; // Красим текст в красный
        return; // Останавливаем выполнение функции, дальше не идем
    }

    try {
        // =====================================================================
        // 3. ОТПРАВКА ЗАПРОСА НА СЕРВЕР (FETCH)
        // =====================================================================
        // await означает "подожди, пока сервер не ответит, прежде чем идти к следующей строчке"
        const response = await fetch("http://127.0.0.1:8000/register", {
            method: "POST", // Метод POST используется для отправки новых данных
            headers: {
                // Говорим серверу (FastAPI), что мы прислали ему именно JSON, а не картинку или просто текст
                "Content-Type": "application/json"
            },
            // JSON.stringify берет наш JavaScript-объект и превращает его в текстовую строку (JSON), 
            // потому что по интернету можно передавать только текст.
            body: JSON.stringify({
                name: enteredName,
                password: enteredPassword
            })
        });

        // Сервер прислал ответ. Он тоже в формате JSON. Мы распаковываем его обратно в JS-объект.
        const data = await response.json();

        // =====================================================================
        // 4. ОБРАБОТКА ОТВЕТА
        // =====================================================================
        
        // Свойство response.ok равно true, если сервер вернул статус 200 (Всё хорошо).
        // Оно равно false, если сервер кинул ошибку (например, 400 - "Такое имя уже занято").
        if (!response.ok) {
            statusP.innerText = "Ошибка: " + data.detail; // data.detail - это то, что мы писали в HTTPException в Python
            statusP.style.color = "red";
            return; // Выходим
        }

        // Если мы дошли сюда, значит регистрация прошла успешно!
        statusP.innerText = data.message; // "Пользователь ... зарегистрирован!"
        statusP.style.color = "green";
        
        // Очищаем поля ввода, чтобы было красиво
        nameInput.value = "";
        passwordInput.value = "";

    } catch (error) {
        // Этот блок сработает, если, например, твой Python сервер выключен или пропал интернет.
        console.error("Ошибка сети:", error);
        statusP.innerText = "Не удалось подключиться к серверу! Включи Python сервер.";
        statusP.style.color = "red";
    }
});